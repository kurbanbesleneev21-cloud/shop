"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { AlertTriangle, Eye, FileText, Loader2, RefreshCw, Save, Sparkles, Trash2, Wand2, X, ArrowRight } from "lucide-react";
import { AnimatePresence, motion } from "motion/react";
import { useApp } from "../providers";
import { ImageUploader } from "../ui/image-uploader";
import { ProductCard } from "../shop/product-card";
import { Card, F, Lines } from "./product-editor";
import type { AiOutput } from "@/lib/ai";
import { api } from "@/lib/client-api";
import { formatDate } from "@/lib/utils";

type Cat = { id: string; slug: string; name: string; template: { key: string; label: string; filter?: string }[] };
type Draft = { id: string; input: Record<string, string>; output: AiOutput; status: string; productId: string | null; createdAt: string };

async function toDataUrl(url: string): Promise<string | null> {
  try {
    const blob = await (await fetch(url)).blob();
    const bmp = await createImageBitmap(blob);
    const scale = Math.min(1, 1024 / Math.max(bmp.width, bmp.height));
    const c = document.createElement("canvas");
    c.width = Math.round(bmp.width * scale);
    c.height = Math.round(bmp.height * scale);
    c.getContext("2d")!.drawImage(bmp, 0, 0, c.width, c.height);
    return c.toDataURL("image/jpeg", 0.85);
  } catch {
    return null;
  }
}

export function AiView({ configured, provider, categories, brands, drafts }: { configured: boolean; provider: string; categories: Cat[]; brands: { id: string; name: string }[]; drafts: Draft[] }) {
  const { toast } = useApp();
  const router = useRouter();
  const [input, setInput] = useState({ title: "", brand: "", model: "", specs: "", wishes: "" });
  const [photos, setPhotos] = useState<string[]>([]);
  const [out, setOut] = useState<AiOutput | null>(null);
  const [draftId, setDraftId] = useState<string | undefined>();
  const [busy, setBusy] = useState("");
  const [preview, setPreview] = useState(false);

  const cat = categories.find((c) => c.slug === out?.categorySlug);
  const setO = <K extends keyof AiOutput>(k: K, v: AiOutput[K]) => setOut((o) => (o ? { ...o, [k]: v } : o));

  async function generate() {
    if (input.title.trim().length < 2) return toast("Введите название товара", "error");
    setBusy("gen");
    try {
      const image = photos[0] ? await toDataUrl(photos[0]) : null;
      const r = await api<{ output: AiOutput }>("/api/admin/ai", { body: { ...input, image } });
      setOut(r.output);
      toast("Карточка сгенерирована — проверьте и отредактируйте");
    } catch (e) {
      toast((e as Error).message, "error");
    } finally {
      setBusy("");
    }
  }

  async function saveDraft() {
    if (!out) return;
    setBusy("draft");
    try {
      const r = await api<{ id: string }>("/api/admin/ai/drafts", { body: { id: draftId, input: { ...input, photos: photos.join(",") }, output: out } });
      setDraftId(r.id);
      toast("Черновик сохранён");
      router.refresh();
    } catch (e) {
      toast((e as Error).message, "error");
    } finally {
      setBusy("");
    }
  }

  async function createProduct() {
    if (!out) return;
    if (!cat) return toast("Выберите категорию", "error");
    setBusy("create");
    try {
      const brandId = brands.find((b) => b.name.toLowerCase() === (out.brand || input.brand).toLowerCase())?.id ?? null;
      const filters: Record<string, string> = {};
      cat.template.forEach((t) => t.filter && out.specs[t.key] && (filters[t.filter] = out.specs[t.key]));
      // Price is never generated by AI: the product is created as a DRAFT with a placeholder price that the admin must set before publishing
      const r = await api<{ id: string }>("/api/manage/products", {
        body: {
          title: out.title, categoryId: cat.id, brandId, model: out.model, price: 1, stock: 0, status: "DRAFT",
          shortDescription: out.shortDescription, description: out.description, advantages: out.advantages, features: out.features, equipment: out.equipment,
          specs: out.specs, seoTitle: out.seoTitle, seoDescription: out.seoDescription, keywords: out.keywords.join(", "), aiGenerated: true,
          color: filters.color ?? null, memory: filters.memory ?? null, diagonal: filters.diagonal ?? null, processor: filters.processor ?? null,
          images: photos.map((url) => ({ url })),
        },
      });
      await api("/api/admin/ai/drafts", { body: { id: draftId, input: { ...input, photos: photos.join(",") }, output: out, status: "PUBLISHED", productId: r.id } });
      toast("Черновик товара создан. Укажите цену, остаток и опубликуйте.");
      router.push(`/admin/products/${r.id}`);
    } catch (e) {
      toast((e as Error).message, "error");
    } finally {
      setBusy("");
    }
  }

  function loadDraft(d: Draft) {
    setDraftId(d.id);
    setInput({ title: d.input.title ?? "", brand: d.input.brand ?? "", model: d.input.model ?? "", specs: d.input.specs ?? "", wishes: d.input.wishes ?? "" });
    setPhotos((d.input.photos ?? "").split(",").filter(Boolean));
    setOut(d.output);
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  return (
    <div className="space-y-5">
      {!configured && (
        <div className="flex flex-wrap items-start gap-3 rounded-card border-2 border-brand-200 bg-brand-50 p-4 text-sm">
          <AlertTriangle className="shrink-0 text-brand" />
          <div className="flex-1">
            <b>Подключите бесплатную нейросеть.</b> Получите бесплатный API-ключ: <a className="link" href="https://aistudio.google.com/apikey" target="_blank" rel="noreferrer">Google Gemini</a>, <a className="link" href="https://console.groq.com/keys" target="_blank" rel="noreferrer">Groq</a> или <a className="link" href="https://openrouter.ai/keys" target="_blank" rel="noreferrer">OpenRouter</a> и вставьте его в <a className="link" href="/admin/settings">Глобальные настройки → AI</a>. Ключ хранится только на сервере.
          </div>
        </div>
      )}
      <div className="grid gap-5 xl:grid-cols-[420px_1fr]">
        <Card title="Исходные данные" subtitle={`Провайдер: ${provider}. AI использует только то, что вы укажете.`}>
          <F label="Название товара *"><input className="input" value={input.title} onChange={(e) => setInput({ ...input, title: e.target.value })} placeholder="Например, Samsung Galaxy S25 256 ГБ" /></F>
          <div className="grid grid-cols-2 gap-3">
            <F label="Бренд"><input className="input" list="ai-brands" value={input.brand} onChange={(e) => setInput({ ...input, brand: e.target.value })} /></F>
            <F label="Модель"><input className="input" value={input.model} onChange={(e) => setInput({ ...input, model: e.target.value })} /></F>
          </div>
          <datalist id="ai-brands">{brands.map((b) => <option key={b.id} value={b.name} />)}</datalist>
          <F label="Технические характеристики" hint="по одной в строке"><textarea className="textarea min-h-[140px]" value={input.specs} onChange={(e) => setInput({ ...input, specs: e.target.value })} placeholder={"Процессор: Snapdragon 8 Elite\nОЗУ: 12 ГБ\nПамять: 256 ГБ\nЭкран: 6.2\" 2340×1080, 120 Гц\nАккумулятор: 4000 мА·ч"} /></F>
          <F label="Дополнительные пожелания"><textarea className="textarea min-h-[70px]" value={input.wishes} onChange={(e) => setInput({ ...input, wishes: e.target.value })} placeholder="Акцент на камере, для молодой аудитории…" /></F>
          <F label="Фотография товара"><ImageUploader value={photos} onChange={setPhotos} max={10} purpose="ai" label="Загрузить фото" /></F>
          <button className="btn-primary btn-lg w-full" disabled={busy === "gen"} onClick={generate}>{busy === "gen" ? <Loader2 size={18} className="animate-spin" /> : <Wand2 size={18} />}Создать карточку с помощью AI</button>
        </Card>

        <div className="min-w-0">
          {!out ? (
            <div className="grid h-full min-h-[300px] place-items-center rounded-card border-2 border-dashed border-ink-200 bg-white p-8 text-center text-ink-500">
              {busy === "gen" ? (
                <div><Sparkles className="mx-auto animate-pulse text-brand" size={40} /><div className="mt-3 font-semibold text-ink">Нейросеть пишет карточку…</div><div className="mt-4 space-y-2">{[80, 95, 70, 90].map((w, i) => <div key={i} className="skeleton mx-auto h-3" style={{ width: `${w * 3}px` }} />)}</div></div>
              ) : (
                <div><Sparkles className="mx-auto text-brand" size={40} /><div className="mt-3">Заполните данные слева и нажмите «Создать карточку с помощью AI»</div></div>
              )}
            </div>
          ) : (
            <div className="space-y-4">
              {out.needsReview.length > 0 && (
                <div className="rounded-card border-2 border-brand-200 bg-brand-50 p-4 text-sm">
                  <div className="mb-1 flex items-center gap-2 font-bold text-brand"><AlertTriangle size={16} />Проверьте перед публикацией</div>
                  <ul className="list-disc pl-5">{out.needsReview.map((n, i) => <li key={i}>{n}</li>)}</ul>
                </div>
              )}
              <Card title="Сгенерированная карточка" subtitle="Все поля можно отредактировать" actions={<span className="flex items-center gap-1 rounded-full bg-brand-50 px-2.5 py-1 text-xs font-bold text-brand"><Sparkles size={12} />AI</span>}>
                <F label="Название"><input className="input" value={out.title} onChange={(e) => setO("title", e.target.value)} /></F>
                <div className="grid gap-3 sm:grid-cols-3">
                  <F label="Категория (определена автоматически)"><select className="input" value={out.categorySlug} onChange={(e) => setO("categorySlug", e.target.value)}><option value="">Выберите…</option>{categories.map((c) => <option key={c.slug} value={c.slug}>{c.name}</option>)}</select></F>
                  <F label="Бренд"><input className="input" value={out.brand} onChange={(e) => setO("brand", e.target.value)} /></F>
                  <F label="Модель"><input className="input" value={out.model} onChange={(e) => setO("model", e.target.value)} /></F>
                </div>
                <F label="Краткое описание"><textarea className="textarea min-h-[70px]" value={out.shortDescription} onChange={(e) => setO("shortDescription", e.target.value)} /></F>
                <F label="Полное описание"><textarea className="textarea min-h-[200px]" value={out.description} onChange={(e) => setO("description", e.target.value)} /></F>
                <div className="grid gap-3 sm:grid-cols-3">
                  <Lines label="Преимущества" value={out.advantages} onChange={(v) => setO("advantages", v)} />
                  <Lines label="Особенности" value={out.features} onChange={(v) => setO("features", v)} />
                  <Lines label="Комплектация" value={out.equipment} onChange={(v) => setO("equipment", v)} />
                </div>
              </Card>
              <Card title="Характеристики" subtitle={cat ? `Шаблон категории «${cat.name}». Пустые поля — данных не было, заполните вручную.` : "Выберите категорию"}>
                <div className="grid gap-3 sm:grid-cols-2">
                  {cat?.template.map((t) => (
                    <F key={t.key} label={t.label} hint={out.specs[t.key] ? undefined : "нет данных"}>
                      <input className={`input ${out.specs[t.key] ? "" : "border-dashed border-brand-300 bg-brand/5"}`} value={out.specs[t.key] ?? ""} onChange={(e) => setO("specs", { ...out.specs, [t.key]: e.target.value })} placeholder="Укажите, если известно" />
                    </F>
                  ))}
                </div>
              </Card>
              <Card title="SEO">
                <F label="SEO-заголовок" hint={`${out.seoTitle.length}/70`}><input className="input" value={out.seoTitle} onChange={(e) => setO("seoTitle", e.target.value)} /></F>
                <F label="SEO-описание" hint={`${out.seoDescription.length}/160`}><textarea className="textarea min-h-[70px]" value={out.seoDescription} onChange={(e) => setO("seoDescription", e.target.value)} /></F>
                <F label="Поисковые ключевые слова"><input className="input" value={out.keywords.join(", ")} onChange={(e) => setO("keywords", e.target.value.split(",").map((s) => s.trim()))} /></F>
              </Card>
              <div className="sticky bottom-0 z-10 flex flex-wrap gap-2 rounded-card bg-white p-3 shadow-lift">
                <button className="btn-outline" onClick={generate} disabled={!!busy}>{busy === "gen" ? <Loader2 size={16} className="animate-spin" /> : <RefreshCw size={16} />}Сгенерировать заново</button>
                <button className="btn-outline" onClick={() => setPreview(true)}><Eye size={16} />Предпросмотр</button>
                <button className="btn-outline" onClick={saveDraft} disabled={!!busy}>{busy === "draft" ? <Loader2 size={16} className="animate-spin" /> : <Save size={16} />}Сохранить черновик</button>
                <button className="btn-primary ml-auto" onClick={createProduct} disabled={!!busy}>{busy === "create" ? <Loader2 size={16} className="animate-spin" /> : <ArrowRight size={16} />}Подтвердить и создать товар</button>
              </div>
              <p className="text-xs text-ink-500">Товар создаётся как черновик без цены и остатка — AI не публикует непроверенную информацию. Публикация доступна после проверки в редакторе.</p>
            </div>
          )}
        </div>
      </div>

      {drafts.length > 0 && (
        <Card title="Сохранённые AI-черновики">
          <ul className="divide-y divide-ink-100">
            {drafts.map((d) => (
              <li key={d.id} className="flex flex-wrap items-center gap-3 py-2.5 text-sm">
                <FileText size={16} className="text-brand" />
                <span className="flex-1 font-medium">{d.output.title || d.input.title}</span>
                <span className="text-xs text-ink-500">{formatDate(d.createdAt, true)} · {d.status === "PUBLISHED" ? "товар создан" : "черновик"}</span>
                {d.productId ? <a href={`/admin/products/${d.productId}`} className="btn-ghost btn-sm">Открыть товар</a> : <button className="btn-soft btn-sm" onClick={() => loadDraft(d)}>Продолжить</button>}
                <button className="grid h-8 w-8 place-items-center rounded-lg hover:bg-ink-100" aria-label="Удалить" onClick={async () => { await api(`/api/admin/ai/drafts/${d.id}`, { method: "DELETE" }); router.refresh(); }}><Trash2 size={15} /></button>
              </li>
            ))}
          </ul>
        </Card>
      )}

      <AnimatePresence>
        {preview && out && (
          <motion.div className="fixed inset-0 z-[90] grid place-items-center overflow-y-auto bg-ink/60 p-4" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={() => setPreview(false)}>
            <motion.div initial={{ y: 20 }} animate={{ y: 0 }} onClick={(e) => e.stopPropagation()} className="w-full max-w-3xl rounded-3xl bg-white p-6">
              <div className="mb-4 flex items-center justify-between"><b className="text-lg">Предпросмотр</b><button onClick={() => setPreview(false)} className="grid h-10 w-10 place-items-center rounded-full hover:bg-ink-100"><X /></button></div>
              <div className="grid gap-6 sm:grid-cols-[220px_1fr]">
                <ProductCard p={{ id: "ai", title: out.title, slug: "preview", price: 0, oldPrice: null, rating: 0, reviewsCount: 0, stock: 0, isNew: true, isHit: false, brand: out.brand ? { name: out.brand } : null, images: photos.map((url) => ({ url })) }} />
                <div className="text-sm">
                  <h3 className="text-xl font-extrabold">{out.title}</h3>
                  <p className="mt-2 text-ink-600">{out.shortDescription}</p>
                  <p className="mt-3 whitespace-pre-line text-ink-700">{out.description}</p>
                  <ul className="mt-3 list-disc pl-5">{out.advantages.map((a) => <li key={a}>{a}</li>)}</ul>
                </div>
              </div>
            </motion.div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
